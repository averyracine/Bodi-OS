// Bundles assets/brand-icons/*.svg into src/lib/brand-icon-data.ts as data: URIs,
// so logos render with no network requests. Rejects anything that could run
// script or load external content.
//   node scripts/gen-brand-icons.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "assets/brand-icons");
const UNSAFE = /<script|<foreignObject|\bon[a-z]+\s*=|<image|<style|href\s*=\s*"(?!#)|url\((?!#)|@import/i;

const out = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(path.join(dir, file), "utf8").trim();
  if (!svg.startsWith("<svg") || !/viewBox=/.test(svg)) throw new Error(`${file}: not a standalone SVG with a viewBox`);
  if (UNSAFE.test(svg)) throw new Error(`${file}: contains disallowed content (${svg.match(UNSAFE)[0]})`);
  if (svg.length > 20_000) throw new Error(`${file}: too large`);
  out[file.replace(/\.svg$/, "")] = `data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}`;
}

const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
writeFileSync(
  path.join(root, "src/lib/brand-icon-data.ts"),
  `// Generated by scripts/gen-brand-icons.mjs from assets/brand-icons/. Do not edit by hand.\n// Sources and licensing notes: assets/brand-icons/SOURCES.md\n\nexport const BRAND_ICON_DATA: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`wrote ${Object.keys(out).length} icons to src/lib/brand-icon-data.ts`);
